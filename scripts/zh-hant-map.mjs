export const CHARS = (() => {
  const map = new Map();
  for (const pair of [...CHAR_PAIRS, ...CHAR_PAIRS_2, ...CHAR_PAIRS_3, ...CHAR_PAIRS_4, ...CHAR_PAIRS_5]) {
    if ([...pair].length !== 2) throw new Error(`简繁对必须是两个字：${pair}`);
    const [s, t] = [...pair];
    if (map.has(s) && map.get(s) !== t) throw new Error(`同一个简体字映射到两个繁体：${s} → ${map.get(s)} / ${t}（请人工定夺）`);
    map.set(s, t);
  }
  return Object.fromEntries(map);
})();




/** 会被替换掉的简体字集合（用于判断"这句本该变、却没变"） */
export const SIMPLIFIED_ONLY = new Set(Object.keys(CHARS));

/** 中文 → 繁体（词表优先、长的先替；再逐字） */
export function toHant(text) {
  let out = String(text);
  const terms = Object.entries(TERMS).sort((a, b) => b[0].length - a[0].length);
  for (const [zh, tw] of terms) if (out.includes(zh)) out = out.split(zh).join(tw);
  return [...out].map((c) => CHARS[c] ?? c).join('');
}
